def largest_n_digit_mul(n: int) -> int:
    q = deque()
    mult = 1
    zc = 0
    for v in num[:n]:
        q.append(v)
        mult *= v
        if v == 0:
            zc += 1
    
    ma = mult
    for v in num[n:]:
        l = q.popleft()
        if l == 0:
            zc -= 1
            if zc == 0:
                mult = reduce(mul, q, 1)
        else:
            mult //= l

        if v == 0:
            zc += 1
        mult *= v
        q.append(v)

        ma = max(ma, mult)

    return ma

